export type Map = "Chernarus" | "Livonia" | "Sakhal";
export type Tier = 1 | 2 | 3 | 4;

export interface Characteristics {
  // Physical
  weightGrams: number;       // exact grams from game file
  sizeRows: number;          // inventory grid rows
  sizeCols: number;          // inventory grid columns
  lengthCm?: number;         // physical length in cm
  absorbency?: number;       // % liquid absorbency
  // Weapon-specific
  fireModes?: string[];      // e.g. ["Semi", "Full Auto"]
  magazineSize?: number;     // max rounds
  reloadTimeSec?: number;    // full reload seconds
  distanceM?: number;        // effective range metres
  muzzleVelocity?: number;   // m/s
  // Gear-specific
  cargoSlots?: number;       // storage capacity (for bags/vests)
  // Food-specific
  nutritionalValue?: number; // kcal
  waterContent?: number;     // ml
  // Medical-specific
  uses?: number;             // number of uses per item
}

export interface Performance {
  // Weapons
  healthDamage?: number;
  shockDamage?: number;
  rpm?: number;
  recoil?: number;           // out of 700, lower = better
  sway?: number;             // out of 5.625, lower = better
  penetrationPower?: number; // muzzle velocity based
  // Gear
  healthReduction?: number;  // % damage reduction vs health
  bloodReduction?: number;   // % damage reduction vs blood
  shockReduction?: number;   // % damage reduction vs shock
  // Food
  energyBoost?: number;      // energy restored
  waterBoost?: number;       // hydration restored
}

